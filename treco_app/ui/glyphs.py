def _draw(shapes, size):
    factor = size / GRID
    width = max(1, round(STROKE * factor))
    mask = Image.new("L", (size, size), 0)
    d = ImageDraw.Draw(mask)
    for shape in shapes:
        kind, values = shape[0], [v * factor for v in shape[1:]]
        if kind == "L":
            d.line(values, fill=255, width=width, joint="curve")
        elif kind == "P":
            d.line(values + values[:4], fill=255, width=width, joint="curve")
        elif kind == "F":
            d.polygon(values, fill=255)
        elif kind == "R":
            d.rectangle(values, outline=255, width=width)
        elif kind == "C":
            x, y, r = values
            d.ellipse((x - r, y - r, x + r, y + r), outline=255, width=width)
        elif kind == "A":
            x, y, r = values[:3]
            d.arc((x - r, y - r, x + r, y + r), shape[4], shape[5], fill=255, width=width)
    return mask


@lru_cache(maxsize=512)
def glyph(name, size):
    """Máscara suave do ícone, com size pixels de lado."""
    if name == "left":
        return ImageOps.mirror(glyph("right", size))
    if name == "flip":
        return glyph("mirror", size).rotate(90)
    big = _draw(SHAPES.get(name, SHAPES["doc"]), size * 4)
    return big.resize((size, size), Image.Resampling.LANCZOS)
